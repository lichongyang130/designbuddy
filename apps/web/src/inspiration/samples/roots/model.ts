export function calculate(s: State) {
  const area = round(s.width * s.depth),
    bed = round(s.bedW * s.bedD * s.bedH * 10),
    pot = round(
      ((Math.PI * (s.potD / 2) ** 2 * s.potH) / 1000) * (1 - s.headroom / 100),
    ),
    litres = round(bed + pot * s.pots),
    bags = Math.ceil(litres / s.bag),
    water = round(
      plants.reduce((a, p, i) => a + p.water * s.qty[i], 0) *
        [1, 1.4, 0.75][s.climate],
    ),
    rain = round(Math.min(s.tank, (s.catchment * s.rain * s.efficiency) / 100)),
    tiles = Math.ceil(((s.pathW * s.pathL) / 0.09) * (1 + s.waste / 100)),
    heads = s.qty.reduce((a, b) => a + b, 0) * s.emitters;
  const rows = [
    ...plants.map((p, i) => ({ name: p.name, qty: s.qty[i], price: p.price })),
    { name: "基质 / " + s.bag + " L", qty: bags, price: round(s.bag * 1.4) },
    { name: "容器", qty: s.pots, price: 120 },
    { name: "30 cm 铺装砖", qty: tiles, price: 16 },
    { name: "灌溉软管 / m", qty: s.hose, price: 8 },
    { name: "滴头", qty: heads, price: 3 },
  ];
  const subtotal = round(rows.reduce((a, r) => a + r.qty * r.price, 0)),
    tax = round((subtotal * s.tax) / 100);
  return {
    area,
    bed,
    pot,
    litres,
    bags,
    water,
    rain,
    topup: round(Math.max(0, water - rain)),
    tiles,
    heads,
    rows,
    subtotal,
    tax,
    total: round(subtotal + tax),
    weight: round(litres * s.density),
    compatible: plants.map((p) => s.sun >= p.light[0] && s.sun <= p.light[1]),
  };
}
