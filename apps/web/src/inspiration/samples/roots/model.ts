export function overlaps(s: State) {
  const pairs: string[] = [];
  for (let i = 0; i < plants.length; i++)
    for (let j = i + 1; j < plants.length; j++)
      if (
        s.qty[i] &&
        s.qty[j] &&
        Math.hypot(
          s.positions[i][0] - s.positions[j][0],
          s.positions[i][1] - s.positions[j][1],
        ) <
          (plants[i].spread + plants[j].spread) / 2
      )
        pairs.push(plants[i].name + " / " + plants[j].name);
  return pairs;
}
const obj = (v: unknown): v is Record<string, unknown> =>
  !!v && typeof v === "object" && !Array.isArray(v);
export function restore(v: unknown): State {
  const s = structuredClone(initial);
  if (!obj(v)) return s;
  for (const k of ["project", "brief", "notes", "reviewer"] as const)
    if (typeof v[k] === "string")
      s[k] = (v[k] as string).slice(
        0,
        k === "notes" || k === "brief" ? 2000 : 80,
      );
  const bounds: Partial<Record<keyof State, [number, number, boolean?]>> = {
    page: [0, 23, true],
    climate: [0, 2, true],
    width: [1, 12],
    depth: [1, 12],
    sun: [0, 12],
    orientation: [0, 3, true],
    soil: [0, 2, true],
    drain: [0, 2, true],
    ph: [3, 10],
    filter: [0, 2, true],
    selected: [0, 4, true],
    bedW: [0.2, 12],
    bedD: [0.2, 12],
    bedH: [10, 60],
    potD: [15, 80],
    potH: [15, 80],
    pots: [0, 20, true],
    headroom: [0, 30],
    bag: [5, 100, true],
    mix: [0, 50],
    density: [0.1, 2],
    catchment: [0, 100],
    rain: [0, 150],
    efficiency: [0, 100],
    tank: [0, 500],
    hose: [0, 100],
    emitters: [1, 5, true],
    pathW: [0.3, 3],
    pathL: [0.3, 12],
    waste: [0, 30],
    month: [0, 11, true],
    budget: [0, 100000],
    tax: [0, 20],
    phase: [0, 6, true],
  };
  for (const [k, [a, b, int]] of Object.entries(bounds)) {
    const n = v[k];
    if (
      typeof n === "number" &&
      Number.isFinite(n) &&
      n >= a &&
      n <= b &&
      (!int || Number.isInteger(n))
    )
      (s as unknown as Record<string, unknown>)[k] = n;
  }
  if (
    Array.isArray(v.qty) &&
    v.qty.length === 5 &&
    v.qty.every((n) => Number.isInteger(n) && n >= 0 && n <= 30)
  )
    s.qty = v.qty;
  if (
    Array.isArray(v.positions) &&
    v.positions.length === 5 &&
    v.positions.every(
      (p) =>
        Array.isArray(p) &&
        p.length === 2 &&
        p.every((n) => typeof n === "number" && Number.isFinite(n)),
    )
  )
    s.positions = v.positions.map((p) => [
      Math.max(20, Math.min(s.width * 100 - 20, p[0])),
      Math.max(20, Math.min(s.depth * 100 - 20, p[1])),
    ]);
  for (const k of ["eco", "checks"] as const)
    if (
      Array.isArray(v[k]) &&
      v[k].length === (k === "eco" ? 3 : 4) &&
      v[k].every((b) => typeof b === "boolean")
    )
      s[k] = v[k];
  if (Array.isArray(v.logs))
    s.logs = v.logs
      .filter(
        (x) =>
          obj(x) &&
          typeof x.date === "string" &&
          typeof x.notes === "string" &&
          Array.isArray(x.checks) &&
          x.checks.length === 4 &&
          x.checks.every((b) => typeof b === "boolean"),
      )
      .slice(0, 8)
      .map((x) => ({
        date: x.date.slice(0, 40),
        notes: x.notes.slice(0, 2000),
        checks: x.checks,
      }));
  if (obj(v.review)) {
    const r = v.review;
    if (
      ["at", "name", "selection"].every((k) => typeof r[k] === "string") &&
      ["total", "area", "water"].every(
        (k) =>
          typeof r[k] === "number" &&
          Number.isFinite(r[k]) &&
          (r[k] as number) >= 0 &&
          (r[k] as number) < 1000000,
      ) &&
      ["confirmed", "withdrawn"].includes(String(r.status))
    )
      s.review = {
        at: (r.at as string).slice(0, 40),
        name: (r.name as string).slice(0, 80),
        selection: (r.selection as string).slice(0, 1000),
        total: r.total as number,
        area: r.area as number,
        water: r.water as number,
        status: r.status as Review["status"],
      };
  }
  s.positions = s.positions.map((p) => [
    Math.max(20, Math.min(s.width * 100 - 20, p[0])),
    Math.max(20, Math.min(s.depth * 100 - 20, p[1])),
  ]);
  s.bedW = Math.min(s.bedW, s.width);
  s.bedD = Math.min(s.bedD, s.depth);
  s.pathW = Math.min(s.pathW, s.width);
  s.pathL = Math.min(s.pathL, s.depth);
  return s;
}
