export function schedule(s: State) {
  const days = 21 + s.construction * 7 + (s.handwork ? 3 : 0) + s.buffer;
  const at = (d: number) =>
    new Date(Date.parse(s.start + "T00:00:00Z") + d * 86400000)
      .toISOString()
      .slice(0, 10);
  return {
    days,
    dates: [
      at(0),
      at(4),
      at(14 + s.construction * 7),
      at(18 + s.construction * 7),
      at(days - 2),
      at(days),
    ],
  };
}
