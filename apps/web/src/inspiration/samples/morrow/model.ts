export const makeQueue = (s: State): Cycle[] =>
  !blendValid(s) ||
  !validDate(s.start) ||
  !validDate(addDays(s.start, s.weeks * 21))
    ? []
    : Array.from({ length: 4 }, (_, i) => ({
        ...item(s),
        date: addDays(s.start, s.weeks * 7 * i),
        skip: false,
      }));
export const balance = (s: State) =>
  round(500 + s.stock.reduce((a, x) => a + x.delta, 0));
export function calculate(s: State) {
  const water = round(s.dose * s.ratio),
    bloom = round(s.dose * 3),
    middle = round((water - bloom) * 0.55),
    last = round(water - bloom - middle),
    active =
      s.mode === 0 ? s.cart : s.paused ? [] : s.queue.filter((x) => !x.skip),
    rows = active.map((x) => ({
      name:
        x.label +
        " / " +
        x.grams +
        "g × " +
        x.qty +
        ("date" in x ? " / " + x.date : ""),
      amount: round(x.qty * x.unit * (1 - s.discount / 100)),
    })),
    coffee = round(rows.reduce((a, r) => a + r.amount, 0)),
    shipping = !active.length
      ? 0
      : s.mode === 0
        ? coffee >= 199
          ? 0
          : 15
        : rows.reduce((a, r) => a + (r.amount >= 199 ? 0 : 15), 0),
    pack = s.mode === 1 && s.paused ? 0 : s.gift * 10;
  rows.push(
    { name: "示例运费", amount: shipping },
    { name: "礼盒预算", amount: pack },
  );
  const subtotal = round(coffee + shipping + pack),
    tax = round((subtotal * s.tax) / 100),
    daily = round(s.persons * s.cups * s.dose);
  return {
    water,
    pours: [bloom, middle, last],
    rows,
    coffee,
    shipping,
    tax,
    total: round(subtotal + tax),
    daily,
    cycleUse: round(daily * s.weeks * 7),
    coverage: round(balance(s) / daily),
    age: Math.round(
      (Date.parse(s.observed) - Date.parse(s.roasted)) / 86400000,
    ),
    recommend: [0, 1, 2].sort(
      (a, b) =>
        beans[a].profile.reduce(
          (t, n, i) => t + (n - s.preferences[i]) ** 2,
          0,
        ) -
        beans[b].profile.reduce(
          (t, n, i) => t + (n - s.preferences[i]) ** 2,
          0,
        ),
    )[0],
  };
}
const obj = (v: unknown): v is Record<string, unknown> =>
  !!v && typeof v === "object" && !Array.isArray(v);
const cleanItem = (x: unknown): Item | null =>
  obj(x) &&
  typeof x.id === "string" &&
  x.id.length > 0 &&
  x.id.length <= 80 &&
  typeof x.label === "string" &&
  [250, 500].includes(x.grams as number) &&
  Number.isInteger(x.qty) &&
  (x.qty as number) >= 1 &&
  (x.qty as number) <= 6 &&
  typeof x.unit === "number" &&
  Number.isFinite(x.unit) &&
  x.unit >= 0 &&
  x.unit <= 10000
