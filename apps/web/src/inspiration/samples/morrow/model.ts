export const validDate = (v: unknown): v is string =>
  typeof v === "string" &&
  /^20\d\d-\d\d-\d\d$/.test(v) &&
  Number.isFinite(Date.parse(v)) &&
  new Date(v + "T00:00:00Z").toISOString().slice(0, 10) === v;
export const addDays = (date: string, n: number) =>
  new Date(Date.parse(date + "T00:00:00Z") + n * 86400000)
    .toISOString()
    .slice(0, 10);
export const blendValid = (s: State) =>
  !s.blend || Math.abs(s.ratios.reduce((a, b) => a + b, 0) - 100) < 0.001;
export const label = (s: State) =>
  s.blend ? "自定义拼配 " + s.ratios.join("/") + "%" : beans[s.bean].name;
export const unit = (s: State) =>
  round(
    (((s.blend
      ? beans.reduce((a, b, i) => a + (b.price * s.ratios[i]) / 100, 0)
      : beans[s.bean].price) *
      s.grams) /
      250) *
      (s.grams === 500 ? 0.95 : 1),
  );
