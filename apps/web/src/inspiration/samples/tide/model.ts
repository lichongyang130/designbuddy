export const time = (n: number) =>
  String(Math.floor(n / 60)).padStart(2, "0") +
  ":" +
  String(n % 60).padStart(2, "0");
export const validDate = (v: unknown): v is string =>
  typeof v === "string" &&
  /^20\d\d-\d\d-\d\d$/.test(v) &&
  Number.isFinite(Date.parse(v)) &&
  new Date(v + "T00:00:00Z").toISOString().slice(0, 10) === v;
export const validMonth = (v: unknown): v is string =>
  typeof v === "string" && /^20\d\d-(0[1-9]|1[0-2])$/.test(v);
export const used = (s: State, month: string) =>
  s.intents
    .filter((b) => !b.cancelled && b.date.startsWith(month))
    .reduce((a, b) => a + b.minutes / 60, 0);
export function intentError(s: State, b: Intent, quota = true) {
  if (
    ![b.boat, b.start, b.minutes, b.people].every(Number.isInteger) ||
    b.boat < 0 ||
    b.boat > 2
  )
    return "参数无效。";
  if (!validDate(b.date)) return "请选择有效日期。";
  if (!b.title.trim()) return "请填写意向主题。";
  if (
    b.start < 480 ||
    b.start + b.minutes > 1080 ||
    b.start % 30 ||
    b.minutes < 30 ||
    b.minutes > 240 ||
    b.minutes % 30
  )
    return "请使用 08:00–18:00 内的 30 分钟刻度，单次 30–240 分钟。";
  if (b.people < 1 || b.people > boats[b.boat].capacity)
    return "人数超过所选船只的示例上限。";
  if (
    s.intents.some(
      (x) =>
        !x.cancelled &&
        x.boat === b.boat &&
        x.date === b.date &&
        x.start < b.start + b.minutes &&
        b.start < x.start + x.minutes,
    )
  )
    return "同船同日的时段已重叠，请调整时间。";
  if (
    quota &&
    used(s, b.date.slice(0, 7)) + b.minutes / 60 > plans[s.plan].hours
  )
    return "该月意向时数超出当前方案上限。";
  if (s.intents.length >= 30) return "已达 30 条意向，请导出后整理。";
  return "";
}
export function calculate(s: State) {
  const current = s.intents.filter(
      (b) => !b.cancelled && b.date.startsWith(s.month),
    ),
    rows = [
      { name: plans[s.plan].name + " / " + s.month, amount: plans[s.plan].fee },
      ...current.map((b) => ({
        name: b.date + " " + time(b.start) + " / " + b.title,
        amount: round(
          ((boats[b.boat].rate + (b.coach ? 180 : 0)) * b.minutes) / 60,
        ),
      })),
      { name: "清洁袋物料", amount: s.bags * 3 },
      { name: "手套物料 / 双", amount: s.gloves * 8 },
    ];
  const subtotal = round(rows.reduce((a, r) => a + r.amount, 0)),
    tax = round((subtotal * s.tax) / 100),
    miles = round(s.legs.reduce((a, b) => a + b, 0)),
    logMiles = round(s.logs.reduce((a, b) => a + b.miles, 0)),
    logMinutes = s.logs.reduce((a, b) => a + b.minutes, 0),
    trialMinutes = s.trials.reduce((a, b) => a + b.minutes, 0);
  return {
    rows,
    subtotal,
    tax,
    total: round(subtotal + tax),
    hours: used(s, s.month),
    remaining: plans[s.plan].hours - used(s, s.month),
    miles,
    km: round(miles * 1.852),
    duration: Math.round((miles / s.speed) * 60),
    logMiles,
    logMinutes,
    logSpeed: logMinutes ? round((logMiles / logMinutes) * 60) : 0,
    trialSpeed: trialMinutes
      ? round((s.trials.reduce((a, b) => a + b.miles, 0) / trialMinutes) * 60)
      : 0,
  };
}
