export const time = (n: number) =>
  String(Math.floor(n / 60)).padStart(2, "0") +
  ":" +
  String(n % 60).padStart(2, "0");
export const validDate = (s: unknown): s is string =>
  typeof s === "string" &&
  /^20\d\d-\d\d-\d\d$/.test(s) &&
  Number.isFinite(Date.parse(s)) &&
  new Date(s + "T00:00:00Z").toISOString().slice(0, 10) === s;
export const cost = (b: Pick<Booking, "resource" | "duration" | "people">) =>
  Math.round(
    ((resources[b.resource].rate * b.duration) / 60) *
      (b.resource === 0 ? b.people : 1) *
      100,
  ) / 100;
export function bookingError(
  s: State,
  b: Pick<
    Booking,
    "resource" | "date" | "start" | "duration" | "people" | "title"
  >,
) {
  if (
    ![b.resource, b.start, b.duration, b.people].every(Number.isInteger) ||
    b.resource < 0 ||
    b.resource > 2
  )
    return "预约参数无效。";
  if (!validDate(b.date)) return "请选择有效日期。";
  if (!b.title.trim()) return "请填写预约主题。";
  if (
    b.start < 480 ||
    b.start + b.duration > 1200 ||
    b.start % 30 ||
    b.duration < 30 ||
    b.duration > 240 ||
    b.duration % 30
  )
    return "时段必须在 08:00–20:00 内，使用 30 分钟刻度，单次 30–240 分钟。";
  if (b.people < 1 || b.people > resources[b.resource].capacity)
    return "人数超过当前资源容量。";
  if (s.bookings.length >= 30) return "本地台账最多保留 30 条，请导出后整理。";
  const active = s.bookings.filter(
    (x) => !x.cancelled && x.resource === b.resource && x.date === b.date,
  );
  for (let t = b.start; t < b.start + b.duration; t += 30) {
    const conflicts = active.filter(
      (x) => x.start <= t && x.start + x.duration > t,
    );
    if (
      b.resource === 0
        ? conflicts.reduce((a, x) => a + x.people, 0) + b.people > 12
        : conflicts.length > 0
    )
      return b.resource === 0
        ? "这个时段工位人数超出容量。"
        : "这个时段已有独占预约，请更换时间。";
  }
  return "";
}
export function estimate(s: State) {
  const passCost = [
    35 * s.days * s.teamSize,
    180 * s.days * s.teamSize,
    2400 * s.teamSize,
  ][s.pass];
  const rows =
    s.billing === 0
      ? s.bookings
          .filter((b) => !b.cancelled)
          .map((b) => ({
            name: `${b.title} / ${b.date} ${time(b.start)}`,
            amount: cost(b),
          }))
      : [
          {
            name: ["按人时通行预算", "按人日通行预算", "按人月通行预算"][
              s.pass
            ],
            amount: passCost,
          },
        ];
  rows.push(
    { name: "咖啡需求", amount: s.coffee * 22 },
    { name: "黑白打印 / 页", amount: s.prints * 0.5 },
    { name: "储物柜 / 日", amount: s.lockers * 15 },
  );
  const subtotal = rows.reduce((a, b) => a + b.amount, 0),
    tax = Math.round(subtotal * s.tax) / 100;
  return {
    rows,
    subtotal,
    tax,
    total: Math.round((subtotal + tax) * 100) / 100,
    passCost,
    energy:
      Math.round(
        (((s.devices * s.watts + s.lighting) * s.hours) / 1000) * 1000,
      ) / 1000,
  };
}
const object = (v: unknown): v is Record<string, unknown> =>
  !!v && typeof v === "object" && !Array.isArray(v);
export function restore(v: unknown): State {
  const s = structuredClone(initial);
  if (!object(v)) return s;
  for (const k of [
    "project",
    "brief",
    "bookingTitle",
    "memberName",
    "ticketText",
    "visitor",
    "feedback",
  ] as const)
    if (typeof v[k] === "string")
      s[k] = (v[k] as string).slice(
        0,
        ["brief", "ticketText", "feedback"].includes(k) ? 2000 : 80,
      );
  for (const k of ["date", "calendarDate", "visitDate"] as const)
    if (validDate(v[k])) s[k] = v[k];
  const bounds: Partial<Record<keyof State, [number, number, boolean?]>> = {
    page: [0, 23, true],
    mode: [0, 2, true],
    teamSize: [1, 12, true],
    resource: [0, 2, true],
    start: [0, 1439, true],
    duration: [30, 240, true],
    people: [1, 12, true],
    pass: [0, 2, true],
    days: [1, 31, true],
    billing: [0, 1, true],
    memberRole: [0, 2, true],
    coffee: [0, 50, true],
    prints: [0, 1000, true],
    lockers: [0, 30, true],
    event: [0, 2, true],
    attendees: [1, 16, true],
    focusMinutes: [1, 120, true],
    focusEnd: [0, Date.now() + 86400000],
    ticketType: [0, 2, true],
    devices: [0, 30, true],
    watts: [0, 500],
    hours: [0, 24],
    lighting: [0, 3000],
    tariff: [0, 20],
    rating: [1, 5, true],
    tax: [0, 20],
    budget: [0, 100000],
  };
  for (const [k, [lo, hi, int]] of Object.entries(bounds)) {
    const n = v[k];
    if (
      typeof n === "number" &&
      Number.isFinite(n) &&
      n >= lo &&
      n <= hi &&
      (!int || Number.isInteger(n))
    )
      (s as unknown as Record<string, unknown>)[k] = n;
  }
  for (const k of ["equipment", "safety"] as const)
    if (
      Array.isArray(v[k]) &&
      v[k].length === (k === "equipment" ? 3 : 4) &&
      v[k].every((x) => typeof x === "boolean")
    )
      s[k] = v[k];
  if (Array.isArray(v.bookings)) {
    s.bookings = [];
    for (const b of v.bookings.slice(0, 30)) {
      if (
        !object(b) ||
        typeof b.id !== "string" ||
        typeof b.title !== "string" ||
        typeof b.checked !== "boolean" ||
        typeof b.cancelled !== "boolean" ||
        !Number.isInteger(b.resource) ||
        (b.resource as number) < 0 ||
        (b.resource as number) > 2 ||
        !["start", "duration", "people"].every((k) => Number.isInteger(b[k]))
      )
        continue;
      const candidate = {
        id: b.id.slice(0, 80),
        title: b.title.slice(0, 80),
        date: String(b.date),
        resource: b.resource as number,
        start: b.start as number,
        duration: b.duration as number,
        people: b.people as number,
        checked: b.checked,
        cancelled: b.cancelled,
      };
      if (s.bookings.some((x) => x.id === candidate.id)) continue;
      if (
        !bookingError(
          candidate.cancelled ? { ...s, bookings: [] } : s,
          candidate,
        )
      )
        s.bookings.push(candidate);
    }
  }
  if (Array.isArray(v.members)) {
    const seen = new Set<string>();
    s.members = v.members
      .filter(
        (m) =>
          object(m) &&
          typeof m.id === "string" &&
          typeof m.name === "string" &&
          [0, 1, 2].includes(m.role as number) &&
          !seen.has(m.id) &&
          !!seen.add(m.id),
      )
      .slice(0, 12)
      .map((m) => ({
        id: m.id.slice(0, 80),
        name: m.name.slice(0, 80),
        role: m.role,
      }));
  }
  const ids = s.members.map((m) => m.id);
  if (Array.isArray(v.seats) && v.seats.length === 12) {
    const used = new Set<string>();
    s.seats = v.seats.map((x) =>
      typeof x === "string" && ids.includes(x) && !used.has(x)
        ? (used.add(x), x)
        : null,
    );
  } else s.seats = s.seats.map((x) => (x && ids.includes(x) ? x : null));
  s.selectedMember =
    typeof v.selectedMember === "string" && ids.includes(v.selectedMember)
      ? v.selectedMember
      : ids[0] || "";
  s.host =
    typeof v.host === "string" && ids.includes(v.host) ? v.host : ids[0] || "";
  if (
    Array.isArray(v.joins) &&
    v.joins.length === 3 &&
    v.joins.every((n, i) => Number.isInteger(n) && n >= 0 && n <= events[i].cap)
  )
    s.joins = v.joins;
  if (Array.isArray(v.tickets))
    s.tickets = v.tickets
      .filter(
        (t) =>
          object(t) &&
          typeof t.id === "string" &&
          typeof t.text === "string" &&
          [0, 1, 2].includes(t.type as number) &&
          typeof t.done === "boolean",
      )
      .slice(0, 10)
      .map((t) => ({
        id: t.id.slice(0, 80),
        text: t.text.slice(0, 2000),
        type: t.type,
        done: t.done,
      }));
  if (Array.isArray(v.visitors))
    s.visitors = v.visitors
      .filter(
        (x) =>
          object(x) &&
          typeof x.name === "string" &&
          validDate(x.date) &&
          typeof x.host === "string" &&
          ids.includes(x.host),
      )
      .slice(0, 12)
      .map((x) => ({ name: x.name.slice(0, 80), date: x.date, host: x.host }));
  if (Array.isArray(v.reviews))
    s.reviews = v.reviews
      .filter(
        (x) =>
          object(x) &&
          typeof x.at === "string" &&
          typeof x.text === "string" &&
          Number.isInteger(x.rating) &&
          (x.rating as number) >= 1 &&
          (x.rating as number) <= 5,
      )
      .slice(0, 10)
      .map((x) => ({
        at: x.at.slice(0, 40),
        text: x.text.slice(0, 2000),
        rating: x.rating,
      }));
  if (object(v.invoice)) {
    const x = v.invoice;
    if (
      ["at", "project", "mode"].every((k) => typeof x[k] === "string") &&
      ["tax", "total"].every(
        (k) =>
          typeof x[k] === "number" &&
          Number.isFinite(x[k]) &&
          (x[k] as number) >= 0 &&
          (x[k] as number) < 1000000,
      ) &&
      Array.isArray(x.rows) &&
      x.rows.length <= 40 &&
      x.rows.every(
        (r) =>
          object(r) &&
          typeof r.name === "string" &&
          typeof r.amount === "number" &&
          Number.isFinite(r.amount) &&
          r.amount >= 0,
      )
    )
      s.invoice = {
        at: (x.at as string).slice(0, 40),
        project: (x.project as string).slice(0, 80),
        mode: (x.mode as string).slice(0, 80),
        tax: x.tax as number,
        total: x.total as number,
        rows: x.rows.map((r) => ({
          name: r.name.slice(0, 180),
          amount: r.amount,
        })),
      };
  }
  return s;
}
