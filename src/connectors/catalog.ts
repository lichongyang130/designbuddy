/** 按 id 找目录条目。 */
export function findConnector(id: string): ConnectorManifest | undefined {
  return CONNECTORS.find((item) => item.id === id)
}

/** 一个连接器会贡献的工具名（`<id>.<tool>`）；写操作默认不算在内。 */
export function toolNamesOf(manifest: ConnectorManifest, options: { allowWrite?: boolean } = {}): string[] {
  return manifest.tools
    .filter((item) => options.allowWrite === true || !item.write)
    .map((item) => manifest.id + '.' + item.name)
}
